"""
generate_data.py - builds the synthetic (simulated) traffic dataset used by the project.
Three road segments, 28 days, 15-minute intervals. Each segment follows a DIFFERENT
speed-density law so that model comparison is meaningful:
  S1 Greenshields (linear), S2 Underwood (exponential), S3 Greenberg (logarithmic).
Sensor faults and missing values are injected on purpose to exercise the SQL cleaning step.
Outputs: ../data/traffic_data.csv, ../data/segments.csv, ../sql/02_seed_data.sql
"""
import numpy as np, pandas as pd, os

rng = np.random.default_rng(2026)
HERE = os.path.dirname(os.path.abspath(__file__))
SEGMENTS = {
    "S1": dict(name="Canal Road Expressway", lanes=2, length=6.4, limit=80, law="GS", vf=82, kj=200, kmax=170),
    "S2": dict(name="Northern Bypass",       lanes=3, length=9.1, limit=110, law="UW", vf=118, km=85, kmax=230),
    "S3": dict(name="Ring Boulevard",        lanes=3, length=4.8, limit=90, law="GB", vm=38, kj=190, kmax=185),
}

def true_speed(p, k):
    if p["law"] == "GS": return p["vf"] * (1 - k / p["kj"])
    if p["law"] == "UW": return p["vf"] * np.exp(-k / p["km"])
    return np.minimum(p["vm"] * np.log(p["kj"] / k), 105.0)

def demand_fraction(ts, day_factor, incident_days):
    h = ts.hour + ts.minute / 60
    wd = 1.0 if ts.dayofweek < 5 else 0.45
    f = 0.04 + wd * (0.62 * np.exp(-((h - 8) / 1.3) ** 2) + 0.72 * np.exp(-((h - 17.5) / 1.6) ** 2))
    f += 0.20 * np.exp(-((h - 13) / 3) ** 2) * (1 if wd == 1 else 1.5)
    if ts.date() in incident_days and 16 <= h <= 19: f += 0.30
    return f * day_factor

times = pd.date_range("2026-09-01 00:00", "2026-09-28 23:45", freq="15min")
days = sorted({t.date() for t in times})
weekdays = [d for d in days if pd.Timestamp(d).dayofweek < 5]
rows = []
for code, p in SEGMENTS.items():
    incident_days = set(rng.choice(np.array(weekdays, dtype=object), 3, replace=False))
    day_factor = {d: rng.normal(1.0, 0.08) for d in days}
    for ts in times:
        f = demand_fraction(ts, day_factor[ts.date()], incident_days) * rng.lognormal(0, 0.12)
        kmax = p["kmax"]
        k = float(np.clip(f * kmax, 1.0, (0.97 * p["kj"]) if "kj" in p else kmax))
        v = max(3.0, float(true_speed(p, k)) * (1 + rng.normal(0, 0.06)))
        q = k * v * (1 + rng.normal(0, 0.02))
        rows.append([code, ts, round(q, 1), round(v, 2), round(k, 2)])
df = pd.DataFrame(rows, columns=["segment_code", "obs_time", "flow_vph", "speed_kmh", "density_vpkm"])

# inject faults: ~1% missing speed, ~0.5% wrong-speed sensor faults
n = len(df)
miss = rng.choice(n, int(0.010 * n), replace=False)
df.loc[miss, "speed_kmh"] = np.nan
fault = rng.choice(np.setdiff1d(np.arange(n), miss), int(0.005 * n), replace=False)
df.loc[fault, "speed_kmh"] = (df.loc[fault, "speed_kmh"] * rng.choice([2.3, 0.15], len(fault))).round(2)

df.to_csv(os.path.join(HERE, "../data/traffic_data.csv"), index=False)
pd.DataFrame([dict(segment_code=c, segment_name=p["name"], lanes=p["lanes"], length_km=p["length"],
                   speed_limit_kmh=p["limit"]) for c, p in SEGMENTS.items()]
             ).to_csv(os.path.join(HERE, "../data/segments.csv"), index=False)

def sqlnum(x): return "NULL" if pd.isna(x) else repr(float(x))
with open(os.path.join(HERE, "../sql/02_seed_data.sql"), "w") as f:
    f.write("USE traffic_fd;\n-- Simulated data generated by python/generate_data.py (seed 2026)\n")
    f.write("INSERT INTO road_segment VALUES\n" + ",\n".join(
        f"('{c}','{p['name']}',{p['lanes']},{p['length']},{p['limit']})" for c, p in SEGMENTS.items()) + ";\n\n")
    for i in range(0, n, 500):
        chunk = df.iloc[i:i + 500]
        vals = ",\n".join(f"('{r.segment_code}','{r.obs_time:%Y-%m-%d %H:%M:%S}',{sqlnum(r.flow_vph)},{sqlnum(r.speed_kmh)},{r.density_vpkm})"
                          for r in chunk.itertuples())
        f.write("INSERT INTO traffic_observation (segment_code, obs_time, flow_vph, speed_kmh, density_vpkm) VALUES\n" + vals + ";\n")
print("rows:", n, "| missing speed:", len(miss), "| injected faults:", len(fault))
